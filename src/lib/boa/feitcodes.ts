export function boeteKop(feit: Feit): string {
  if (!feit.tarief) return "Geen vast bedrag in de boetebase";
  const kop = feit.tarief.split("|")[0]?.trim() ?? "";
  return kop || "Geen vast bedrag in de boetebase";
}

export function zoekFeiten(query: string, lijst: Feit[]): Feit[] {
  const q = query.trim().toLowerCase();
  if (!q) return lijst;
  const delen = q.split(/\s+/).filter(Boolean);
  return lijst.filter((feit) => {
    const hay = [feit.code, feit.titel, feit.artikel, feit.bijzonder, feit.pv, feit.trefwoorden, feit.kwalificatie, feit.afdoeningLabel]
      .join(" ")
      .toLowerCase();
    return delen.every((deel) => hay.includes(deel));
  });
}

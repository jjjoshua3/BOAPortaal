export const WEEKSETS: Vraag[][] = [...BASIS, ...EXTRA_SETS];

export function isoWeek(date: Date): { week: number; jaar: number } {
  const tijdstip = new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
  const dag = tijdstip.getUTCDay() || 7;
  tijdstip.setUTCDate(tijdstip.getUTCDate() + 4 - dag);
  const jaar = tijdstip.getUTCFullYear();
  const start = new Date(Date.UTC(jaar, 0, 1));
  const week = Math.ceil(((tijdstip.getTime() - start.getTime()) / 86400000 + 1) / 7);
  return { week, jaar };
}

export function weeksetOp(date: Date): { week: number; jaar: number; set: number; vragen: Vraag[] } {
  const { week, jaar } = isoWeek(date);
  const set = week % WEEKSETS.length;
  return { week, jaar, set: set + 1, vragen: WEEKSETS[set] ?? WEEKSETS[0] };
}
